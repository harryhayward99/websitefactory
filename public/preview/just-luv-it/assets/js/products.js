window.JLI.formatPrice = function (value) {
  return "£" + Number(value).toFixed(2);
};

window.JLI.getProduct = function (slug) {
  return window.JLI.products.find(function (p) {
    return p.slug === slug;
  });
};

window.JLI.filterProducts = function (opts) {
  opts = opts || {};
  var category = opts.category || "all";
  var query = (opts.query || "").trim().toLowerCase();
  return window.JLI.products.filter(function (p) {
    var catOk =
      category === "all" ||
      p.category === category ||
      (category === "seasonal" && p.tags.indexOf("seasonal") !== -1) ||
      (category === "gifts" && p.tags.indexOf("gifts") !== -1);
    if (!catOk) return false;
    if (!query) return true;
    var hay = [p.name, p.fullName, p.blurb, p.category]
      .concat(p.tags)
      .join(" ")
      .toLowerCase();
    return hay.indexOf(query) !== -1;
  });
};
